export function getInvoiceById(id) {
  return INITIAL_INVOICES.find(inv => inv.id === id) || null;
}

export function getInvoicesByCampaign(campaignId) {
  return INITIAL_INVOICES.filter(inv => inv.campaignId === campaignId);
}

export function getInvoicesByCreator(creatorId) {
  return INITIAL_INVOICES.filter(inv => inv.creatorId === creatorId);
}

export function getInvoicesByPortal(portalType) {
  if (!portalType) return INITIAL_INVOICES;
  return INITIAL_INVOICES.filter(inv => inv.portalType === portalType);
}
