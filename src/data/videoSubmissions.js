// Helper to compute live post performance metrics for PRD 8.9 & 8.10
export function getLivePostsForCampaign(campaignId, submissionsList = INITIAL_SUBMISSIONS) {
  return submissionsList
    .filter(s => s.campaignId === campaignId && (s.stage === 'live_approved' || s.stage === 'payment_approved' || s.livePostUrl))
    .map(sub => {
      const views = sub.views || Math.round((sub.followerCount || 80000) * 1.6 + 45000);
      const likes = sub.likes || Math.round(views * 0.068);
      const comments = sub.comments || Math.round(likes * 0.035);
      const reach = sub.reach || Math.round(views * 0.84);
      const engagementRate = sub.engagementRate || Number(((likes + comments) / reach * 100).toFixed(1));
      return {
        ...sub,
        views,
        likes,
        comments,
        reach,
        engagementRate,
        livePostStatus: sub.livePostStatus || 'Live',
        lastMetricsUpdated: sub.lastMetricsUpdated || '2026-09-11 12:00 IST',
        metricsSource: sub.metricsSource || 'Auto (API)',
        reviewedBy: sub.reviewedBy || 'Haulpack Team',
      };
    });
}

export function getCampaignSocialKPIs(campaignId, submissionsList = INITIAL_SUBMISSIONS) {
  const livePosts = getLivePostsForCampaign(campaignId, submissionsList);
  const totalViews = livePosts.reduce((sum, p) => sum + p.views, 0);
  const totalReach = livePosts.reduce((sum, p) => sum + p.reach, 0);
  const totalLikes = livePosts.reduce((sum, p) => sum + p.likes, 0);
  const totalComments = livePosts.reduce((sum, p) => sum + p.comments, 0);
  const avgER = totalReach > 0 ? Number(((totalLikes + totalComments) / totalReach * 100).toFixed(1)) : 0;

  return {
    livePostsCount: livePosts.length,
    totalViews,
    totalReach,
    totalLikes,
    totalComments,
    avgEngagementRate: avgER,
    livePosts,
  };
}

